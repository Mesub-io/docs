// Checks that no author prompt is published. A page's prompt (what it was
// written from: repository paths, notes for whoever edits it) lives in
// prompts/, never in the page: Holocron publishes a page's whole frontmatter,
// in the built site's data and in the raw markdown it serves (each page's .md
// copy, docs.zip, "Ask AI"). Run after `pnpm build`:
//
//   node scripts/check-prompts.mjs
//
// It fails when a page under src/ has a `prompt` field, or when a line of a
// prompt is found in dist/ or in what the built server answers for llms.txt,
// llms-full.txt, docs.zip and every page's .md copy.
import { spawn } from 'node:child_process'
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { createServer } from 'node:net'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { inflateRawSync } from 'node:zlib'

const root = fileURLToPath(new URL('..', import.meta.url))
const failures = []

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })
}

// 1. No page carries a prompt.
const pages = walk(join(root, 'src')).filter((path) => path.endsWith('.mdx'))
for (const path of pages) {
  const head = readFileSync(path, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (head && /^prompt\s*:/m.test(head[1])) {
    failures.push(`${relative(root, path)} has a prompt field: move it to prompts/`)
  }
}

// What a leak looks like: every long line of every prompt, and the note the
// reference generator once wrote.
const needles = new Set(['Generated by @/scripts/reference.mjs'])
for (const path of walk(join(root, 'prompts'))) {
  for (const line of readFileSync(path, 'utf8').split('\n').slice(1)) {
    if (line.trim().length >= 40) needles.add(line.trim())
  }
}

function search(where, text) {
  for (const needle of needles) {
    if (text.includes(needle)) failures.push(`${where} serves a prompt: "${needle}"`)
  }
}

// 2. Nothing of the built site, client or server, holds one.
const dist = join(root, 'dist')
for (const path of walk(dist)) {
  if (path.includes(`${join(dist, 'node_modules')}`)) continue
  search(relative(root, path), readFileSync(path).toString('utf8'))
}

// The entries of a zip, as fflate's zipSync writes it: sizes in each local header.
function unzip(buffer) {
  const files = []
  let at = 0
  while (buffer.readUInt32LE(at) === 0x04034b50) {
    const method = buffer.readUInt16LE(at + 8)
    const size = buffer.readUInt32LE(at + 18)
    const nameLength = buffer.readUInt16LE(at + 26)
    const extraLength = buffer.readUInt16LE(at + 28)
    const name = buffer.subarray(at + 30, at + 30 + nameLength).toString('utf8')
    const start = at + 30 + nameLength + extraLength
    const data = buffer.subarray(start, start + size)
    files.push([name, (method === 8 ? inflateRawSync(data) : data).toString('utf8')])
    at = start + size
  }
  return files
}

// 3. Nothing the built server answers to an agent holds one.
const port = await new Promise((resolve) => {
  const probe = createServer().listen(0, '127.0.0.1', () => {
    const { port } = probe.address()
    probe.close(() => resolve(port))
  })
})
const server = spawn(process.execPath, ['server.mjs'], {
  cwd: root,
  env: { ...process.env, PORT: String(port), HOST: '127.0.0.1' },
  stdio: 'ignore',
})
const base = `http://127.0.0.1:${port}`

try {
  for (let tries = 0; ; tries += 1) {
    try {
      await fetch(`${base}/llms.txt`)
      break
    } catch (error) {
      if (tries > 100) throw new Error(`the built server never answered on ${base}`)
      await new Promise((resolve) => setTimeout(resolve, 100))
    }
  }

  const routes = ['/llms.txt', '/llms-full.txt', '/index.md'].concat(
    pages
      .map((path) => relative(join(root, 'src'), path).replace(/\.mdx$/, ''))
      .filter((slug) => slug !== 'index')
      .map((slug) => `/${slug}.md`),
  )
  for (const route of routes) {
    const response = await fetch(`${base}${route}`)
    if (!response.ok) failures.push(`${route} answered ${response.status}`)
    search(route, await response.text())
  }

  const zip = await fetch(`${base}/docs.zip`)
  const entries = unzip(Buffer.from(await zip.arrayBuffer()))
  if (entries.length < pages.length) {
    failures.push(`docs.zip holds ${entries.length} files for ${pages.length} pages`)
  }
  for (const [name, text] of entries) search(`docs.zip:${name}`, text)
} finally {
  server.kill()
}

if (failures.length) {
  console.error(failures.join('\n'))
  process.exit(1)
}
console.log(`check-prompts: ${needles.size} prompt lines, none published`)
